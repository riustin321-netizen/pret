#pragma once

#include <chrono>
#include <optional>
#include <stdexcept>
#include <string>
#include <utility>

namespace hellboost {
enum class Source { internet, favorites, history, console };
enum class Outcome { entered_game, failed, cancelled, superseded };

struct Attempt {
    std::string id; // UUID generated by the adapter, unique for every attempt.
    std::string endpoint;
    Source source;
};

struct Result {
    Attempt attempt;
    Outcome outcome;
    std::chrono::milliseconds elapsed;
};

// Pure state machine. The engine adapter supplies actual connection events.
// Calling complete() is NOT evidence that a Steam integration exists.
class ConnectionTracker {
public:
    using Clock = std::chrono::steady_clock;
    using Time = Clock::time_point;

    std::optional<Result> begin(Attempt attempt, Time now) {
        if (attempt.id.empty() || attempt.endpoint.empty())
            throw std::invalid_argument("Attempt ID and endpoint are required");
        if (active_ && active_->attempt.id == attempt.id)
            throw std::invalid_argument("An attempt ID cannot be reused");
        check_time(now);
        auto previous = finish(Outcome::superseded, now);
        active_ = Active{std::move(attempt), now};
        return previous;
    }

    // The adapter MUST preserve the attempt ID across asynchronous callbacks.
    // Stale callbacks and duplicate completion events are ignored.
    std::optional<Result> complete(const std::string& id, Outcome outcome, Time now) {
        if (!active_ || active_->attempt.id != id) return std::nullopt;
        check_time(now);
        return finish(outcome, now);
    }

    bool pending() const { return active_.has_value(); }

private:
    struct Active { Attempt attempt; Time started; };
    std::optional<Active> active_;

    void check_time(Time now) const {
        if (active_ && now < active_->started)
            throw std::invalid_argument("Clock moved before connection start");
    }

    std::optional<Result> finish(Outcome outcome, Time now) {
        if (!active_) return std::nullopt;
        Result result{active_->attempt, outcome,
            std::chrono::duration_cast<std::chrono::milliseconds>(now - active_->started)};
        active_.reset();
        return result;
    }
};
} // namespace hellboost
